import { readFile, writeFile } from "node:fs/promises";
const path = "apps/mobile/src/app/conversations/[id].tsx";
let text = await readFile(path, "utf8");
const importLine = 'import { MessageAttachmentComposer } from "@/features/communication/MessageAttachmentComposer";\n';
const importAnchor = 'import { useSession } from "@/session/SessionContext";\n';
if (!text.includes(importLine)) text = text.replace(importAnchor, importLine + importAnchor);
const anchor = '        <AppButton\n          disabled={contactUnavailable || sending}\n          label={sending ? "Enviando..." : "Enviar mensagem"}\n          onPress={() => void send()}\n        />\n';
const addition = anchor + '        {accessToken && params.id ? (\n          <MessageAttachmentComposer\n            accessToken={accessToken}\n            conversationId={params.id}\n            disabled={contactUnavailable || sending}\n            onUploaded={load}\n          />\n        ) : null}\n';
if (!text.includes("<MessageAttachmentComposer")) text = text.replace(anchor, addition);
await writeFile(path, text);
